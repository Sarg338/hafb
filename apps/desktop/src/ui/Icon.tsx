export type IconName = keyof typeof ICONS;

const sized = new Map<string, string>();

/** The SVG markup for an icon, filled with currentColor so it takes the text colour. */
function markup(name: IconName, size: 16 | 20): string {
  const key = `${name}:${String(size)}`;
  let svg = sized.get(key);
  if (svg === undefined) {
    svg = ICONS[name][size].replace('<svg ', '<svg fill="currentColor" aria-hidden="true" focusable="false" ');
    sized.set(key, svg);
  }
  return svg;
}

/** A Fluent icon. Decorative: give the control around it an accessible name. */
export function Icon({ name, size = 16, className, style }: { name: IconName; size?: 16 | 20; className?: string | undefined; style?: CSSProperties }) {
  return (
    <span
      className={className === undefined ? 'icon' : `icon ${className}`}
      style={{ width: size, height: size, ...style }}
      // Static, bundled SVG files from the icon package; never user content.
      dangerouslySetInnerHTML={{ __html: markup(name, size) }}
    />
  );
}
